"""Contracts shared by the agent, CLI and API.

Depends only on Pydantic, so any interface can import it without
pulling HTTP clients, database drivers or configuration.
"""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class PubMedSearchArgs(BaseModel):
    # Arguments the caller provides. Run metadata (run_id, preset variant
    # and version) is resolved by the application, never by the caller
    model_config = ConfigDict(
        extra="forbid",
        strict=True,
        str_strip_whitespace=True,
    )

    query: str = Field(
        min_length=1,
        description=(
            "Complete PubMed expression, ready to run, using Boolean "
            "operators and field tags such as [Title/Abstract] and "
            "[MeSH Terms]. Any date filter must be written explicitly "
            "in the expression."
        ),
    )

    limit: int = Field(
        ge=1,
        le=10_000,
        description="Maximum number of PMIDs requested for this search.",
    )


class PubMedCollectionResult(BaseModel):
    # Return of the persisted PubMed collection (collect_pubmed).
    # Interfaces receive model_dump(mode="json"): a JSON serializable dict.
    # Raw responses and full metadata stay in PostgreSQL, not here
    model_config = ConfigDict(extra="forbid")

    status: Literal["success", "error"] = Field(
        description=(
            "success only after the transaction is committed. "
            "An empty search is a success with zero counts."
        ),
    )
    source: Literal["pubmed"] = "pubmed"
    run_id: str = Field(description="Identifier generated by the application.")
    query: str = Field(description="PubMed expression actually executed.")
    requested_count: int = Field(ge=1, description="Limit requested.")
    total_results: int = Field(
        default=0,
        ge=0,
        description="Records matching the query in PubMed.",
    )
    retrieved_count: int = Field(
        default=0,
        ge=0,
        description="PMIDs returned by ESearch.",
    )
    parsed_count: int = Field(
        default=0,
        ge=0,
        description="Citations parsed from the EFetch XML.",
    )
    saved_count: int = Field(
        default=0,
        ge=0,
        description="Citations committed to PostgreSQL.",
    )
    pmids: list[str] = Field(
        default_factory=list,
        description="PMIDs retrieved, in the order returned by PubMed.",
    )
    warnings: list[str] = Field(
        default_factory=list,
        description="Warnings reported by the source, such as ignored phrases.",
    )
    error: str | None = Field(
        default=None,
        description="Failure description; present only when status is error.",
    )

    @model_validator(mode="after")
    def check_status_consistency(self) -> "PubMedCollectionResult":
        # A failure rolls back the transaction: it can never claim saved data
        if self.status == "error":
            if not self.error:
                raise ValueError("an error result must describe the failure")
            if self.saved_count:
                raise ValueError("an error result cannot report saved citations")

        elif self.error is not None:
            raise ValueError("a success result cannot carry an error")

        return self
